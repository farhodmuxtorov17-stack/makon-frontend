export function unitsOfBuilding(buildingId: string) {
  return UNITS.filter((u) => u.buildingId === buildingId)
}

export function unitsOfFloor(buildingId: string, floor: number) {
  return UNITS.filter((u) => u.buildingId === buildingId && u.floor === floor)
}

export function unitById(id: string) {
  return UNITS.find((u) => u.id === id)
}

